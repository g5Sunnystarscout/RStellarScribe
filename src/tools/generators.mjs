/** Indent a raw script body by `depth` tabs and reject unbalanced input. */
export function blockBody(name, raw, depth = 1) {
  const text = String(raw ?? '').trim();
  if (text === '') return null;
  const structure = checkScriptStructure(text, `\`${name}\``);
  if (structure.errors.length > 0) {
    throw new ToolError(
      `the \`${name}\` block is not valid script:\n- ` +
        structure.errors.map((error) => `line ${error.line}: ${error.message}`).join('\n- '),
    );
  }
  const indent = '\t'.repeat(depth);
  return text
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : indent + line.replace(/^\t+/, '')))
    .join('\n');
}

export function block(name, raw, depth = 1) {
  const body = blockBody(name, raw, depth + 1);
  const indent = '\t'.repeat(depth);
  if (body === null) return `${indent}${name} = { }`;
  return `${indent}${name} = {\n${body}\n${indent}}`;
}

export function blockFromLines(name, lines, depth = 1) {
  const indent = '\t'.repeat(depth);
  if (lines.length === 0) return `${indent}${name} = { }`;
  return `${indent}${name} = {\n${lines.map((line) => `${indent}\t${line}`).join('\n')}\n${indent}}`;
}

export function quoteList(values) {
  return values.map((value) => `"${escapeScriptString(value)}"`).join(' ');
}

export function assertLanguage(language) {
  const resolved = normaliseLanguage(language ?? 'english');
  if (!LOCALISATION_LANGUAGES.includes(resolved)) {
    throw new ToolError(`unknown language \`${language}\``);
  }
  return resolved;
}

export function localisationPlan({ language, path, entries, summary }) {
  return generatedFile(path, renderLocalisationFile({ language, entries }), {
    encoding: ENCODING_UTF8_BOM,
    summary,
  });
}

/** Definition keys must be lowercase ASCII: non-ASCII keys break script parsing. */
export function requireDefinitionKey(value, field) {
  const key = requireString(value, field);
  if (!/^[a-z0-9_.]+$/.test(key)) {
    throw new ToolError(
      `\`${field}\` must be a lowercase ASCII key (letters, digits, underscore, dot); received \`${key}\``,
    );
  }
  return key;
}

