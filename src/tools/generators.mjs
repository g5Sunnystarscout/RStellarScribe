export const SCRIPT_HEADER = (path, source) =>
  `# Generated by RStellarScribe for ${path}.\n# Field names follow the installed game's own files; see ${source}.\n\n`;

/**
 * The event type keywords Stellaris 4.4.6 uses as top-level blocks in `events/`.
 *
 * A namespace is NOT an event type. Writing `<namespace>_event = { ... }` makes the engine
 * report `Corrupt Event Table Entry` once per token in the block and register no event at
 * all - a live game test produced 20 such errors from one event before this list existed.
 */
export const EVENT_TYPES = new Set([
  'agreement_event',
  'astral_rift_event',
  'bypass_event',
  'country_event',
  'espionage_operation_event',
  'first_contact_event',
  'fleet_event',
  'leader_event',
  'observer_event',
  'planet_event',
  'pop_faction_event',
  'pop_group_event',
  'ship_event',
  'situation_event',
  'starbase_event',
  'system_event',
]);

