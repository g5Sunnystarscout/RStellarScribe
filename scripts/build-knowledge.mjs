import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { readKnowledgeSources } from '../src/lib/knowledge-source.mjs';
import { topicToToml } from '../src/lib/knowledge.mjs';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const knowledgeRoot = join(projectRoot, 'knowledge');
const canonicalRoot = join(projectRoot, 'resources', 'knowledge', 'stellaris');
const generatedDir = join(projectRoot, 'src', 'generated');
const generatedPath = join(generatedDir, 'knowledge.mjs');

function main() {
  const topics = readKnowledgeSources(knowledgeRoot);

  rmSync(canonicalRoot, { recursive: true, force: true });

  for (const topic of topics) {
    const relativePath = canonicalTopicPath(topic);
    const target = join(canonicalRoot, relativePath);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, topicToToml(topic), 'utf8');
  }

  const latestUpdate = readLatestUpdate();
  const sourcePaths = topics.map((topic) => canonicalTopicPath(topic).split('\\').join('/'));
  const snapshot = topics.map((topic) => ({
    ...topic,
    source_path: canonicalTopicPath(topic).split('\\').join('/'),
  }));

  mkdirSync(generatedDir, { recursive: true });
  const module = [
    '// Generated by scripts/build-knowledge.mjs. Do not edit by hand.',
    '// This mirrors RHoiScribe\'s build.rs compile-time knowledge embedding.',
    '',
    `export const topics = ${JSON.stringify(snapshot, null, 2)};`,
    '',
    `export const sourcePaths = ${JSON.stringify(sourcePaths, null, 2)};`,
    '',
    `export const latestUpdate = ${JSON.stringify(latestUpdate, null, 2)};`,
    '',
  ].join('\n');
  writeFileSync(generatedPath, module, 'utf8');

  const byCategory = new Map();
  for (const topic of topics) {
    byCategory.set(topic.category, (byCategory.get(topic.category) ?? 0) + 1);
  }
  const summary = [...byCategory.entries()]
    .sort()
    .map(([category, count]) => `${category}=${count}`)
    .join(' ');
  process.stdout.write(
    `built ${topics.length} knowledge topics (${summary})\n` +
      `  canonical: resources/knowledge/stellaris/\n` +
      `  snapshot:  src/generated/knowledge.mjs\n`,
  );
}

/**
 * Group the canonical TOML by category, the way RHoiScribe groups its topic files.
 * A dotted id loses its first segment, so id `localisation.encoding` with category
 * `localisation` becomes `localisation/encoding.toml`, exactly as in the original,
 * while a flat id such as `mod-structure` becomes `structure/mod-structure.toml`.
 */
function canonicalTopicPath(topic) {
  const segments = topic.id.split('.');
  const tail = segments.length === 1 ? topic.id : segments.slice(1).join('.');
  return `${topic.category}/${tail}.toml`;
}

function readLatestUpdate() {
  const path = join(knowledgeRoot, 'updates', 'latest-update.md');
  try {
    const text = readFileSync(path, 'utf8').replace(/^\uFEFF/, '');
    const end = text.indexOf('\n---', 3);
    const frontMatter = text.slice(text.indexOf('\n', 3) + 1, end);
    const titleLine = /^title:\s*(.*)$/m.exec(frontMatter);
    const body = text.slice(text.indexOf('\n', end + 1) + 1).trim();
    return {
      title: titleLine ? titleLine[1].trim().replace(/^["']|["']$/g, '') : 'Stellaris latest update',
      body,
    };
  } catch {
    return {
      title: 'Stellaris latest update',
      body: 'No bundled update snapshot is present in this checkout.',
    };
  }
}

main();
